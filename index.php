<script>
  document.addEventListener('DOMContentLoaded', function () {
    // 1. Testimonial Slider
    const track = document.getElementById('testimonialTrack');
    const slides = track ? track.querySelectorAll('.testimonial-slide') : [];
    const dots = document.querySelectorAll('.slider-dot');
    const prevBtn = document.getElementById('prevSlide');
    const nextBtn = document.getElementById('nextSlide');
    let currentIndex = 0;

    function updateSlider(index) {
      if (!track || slides.length === 0) return;
      if (index < 0) index = slides.length - 1;
      if (index >= slides.length) index = 0;
      currentIndex = index;
      track.style.transform = 'translateX(-' + (currentIndex * 100) + '%)';
      dots.forEach((dot, dIdx) => {
        dot.classList.toggle('is-active', dIdx === currentIndex);
      });
    }

    if (prevBtn && nextBtn) {
      prevBtn.addEventListener('click', () => updateSlider(currentIndex - 1));
      nextBtn.addEventListener('click', () => updateSlider(currentIndex + 1));
      dots.forEach(dot => {
        dot.addEventListener('click', () => updateSlider(parseInt(dot.getAttribute('data-index'), 10)));
      });
    }

    // 2. FAQ Accordion
    const faqUnits = document.querySelectorAll('.faq-unit');
    faqUnits.forEach(unit => {
      const btn = unit.querySelector('button');
      const content = unit.querySelector('.faq-content');
      
      btn.addEventListener('click', () => {
        const isOpen = unit.classList.contains('is-open');
        faqUnits.forEach(u => {
          u.classList.remove('is-open');
          u.querySelector('button').setAttribute('aria-expanded', 'false');
          u.querySelector('.faq-content').style.maxHeight = null;
        });
        if (!isOpen) {
          unit.classList.add('is-open');
          btn.setAttribute('aria-expanded', 'true');
          content.style.maxHeight = content.scrollHeight + 30 + 'px';
        }
      });
    });

    // 3. Consultation Form Validation
    const intakeForm = document.getElementById('projectIntakeForm');
    if (intakeForm) {
      intakeForm.addEventListener('submit', function (e) {
        e.preventDefault();
        const name = document.getElementById('clientName').value.trim();
        const email = document.getElementById('clientEmail').value.trim();
        const phone = document.getElementById('clientPhone').value.trim();
        const submitBtn = document.getElementById('homeConsultationBtn');
        const btnText = document.getElementById('homeBtnText');
        const statusBox = document.getElementById('formSuccessMessage');

        if (!name || !email || !phone) {
          statusBox.style.display = 'block';
          statusBox.style.background = 'rgba(225, 29, 42, 0.09)';
          statusBox.style.border = '1px solid var(--vpdl-red)';
          statusBox.style.color = 'var(--vpdl-red)';
          statusBox.innerText = 'Please complete all required fields marked with an asterisk (*).';
          return;
        }

        submitBtn.disabled = true;
        if (btnText) btnText.innerText = 'Transmitting Brief...';

        setTimeout(function() {
          statusBox.style.display = 'block';
          statusBox.style.background = 'rgba(16, 185, 129, 0.1)';
          statusBox.style.border = '1px solid #10b981';
          statusBox.style.color = '#065f46';
          statusBox.innerText = 'Thank you. Your consultation brief has been recorded. Our practice directors will review your parameters and follow up within 24 business hours.';
          intakeForm.reset();
          submitBtn.disabled = false;
          if (btnText) btnText.innerText = 'Submit Free Consultation Request';
        }, 1000);
      });
    }

    // 4. Video Dropzone Drag & Select Controller
    const dropzone = document.getElementById('videoDropzone');
    const fileInput = document.getElementById('siteVideoFile');
    const dropzoneContent = document.getElementById('dropzoneContent');
    const selectedChip = document.getElementById('dropzoneSelectedChip');
    const selectedFileName = document.getElementById('selectedVideoName');
    const removeFileBtn = document.getElementById('removeVideoFileBtn');

    if (dropzone && fileInput) {
      dropzone.addEventListener('click', function(e) {
        if (e.target !== removeFileBtn && !selectedChip.contains(e.target)) {
          fileInput.click();
        }
      });

      ['dragenter', 'dragover'].forEach(eventName => {
        dropzone.addEventListener(eventName, function(e) {
          e.preventDefault();
          e.stopPropagation();
          dropzone.classList.add('is-dragover');
        });
      });

      ['dragleave', 'drop'].forEach(eventName => {
        dropzone.addEventListener(eventName, function(e) {
          e.preventDefault();
          e.stopPropagation();
          dropzone.classList.remove('is-dragover');
        });
      });

      dropzone.addEventListener('drop', function(e) {
        if (e.dataTransfer.files && e.dataTransfer.files[0]) {
          fileInput.files = e.dataTransfer.files;
          updateFileState(e.dataTransfer.files[0]);
        }
      });

      fileInput.addEventListener('change', function() {
        if (fileInput.files && fileInput.files[0]) {
          updateFileState(fileInput.files[0]);
        }
      });

      function updateFileState(file) {
        if (!file) return;
        const sizeMb = (file.size / (1024 * 1024)).toFixed(1);
        selectedFileName.innerText = file.name + ' (' + sizeMb + ' MB)';
        dropzoneContent.style.display = 'none';
        selectedChip.style.display = 'inline-flex';
      }

      if (removeFileBtn) {
        removeFileBtn.addEventListener('click', function(e) {
          e.stopPropagation();
          fileInput.value = '';
          selectedChip.style.display = 'none';
          dropzoneContent.style.display = 'block';
        });
      }
    }

    // 5. Video Appraisal Submission Handler
    const videoForm = document.getElementById('videoAppraisalForm');
    if (videoForm) {
      videoForm.addEventListener('submit', function(e) {
        e.preventDefault();
        const vName = document.getElementById('videoClientName').value.trim();
        const vEmail = document.getElementById('videoClientEmail').value.trim();
        const vPhone = document.getElementById('videoClientPhone').value.trim();
        const vLink = document.getElementById('videoCloudLink').value.trim();
        const hasFile = fileInput && fileInput.files && fileInput.files.length > 0;
        const vStatus = document.getElementById('videoSuccessMessage');
        const vBtn = document.getElementById('videoSubmitBtn');
        const vBtnText = document.getElementById('videoBtnText');

        if (!vName || !vEmail || !vPhone) {
          vStatus.style.display = 'block';
          vStatus.style.background = 'rgba(225, 29, 42, 0.09)';
          vStatus.style.border = '1px solid var(--vpdl-red)';
          vStatus.style.color = 'var(--vpdl-red)';
          vStatus.innerText = 'Please ensure your name, email, and telephone number are filled in.';
          return;
        }

        if (!hasFile && !vLink) {
          vStatus.style.display = 'block';
          vStatus.style.background = 'rgba(225, 29, 42, 0.09)';
          vStatus.style.border = '1px solid var(--vpdl-red)';
          vStatus.style.color = 'var(--vpdl-red)';
          vStatus.innerText = 'Please attach a video file (Option A) or paste a cloud link (Option B) for our engineers to review.';
          return;
        }

        vBtn.disabled = true;
        if (vBtnText) vBtnText.innerText = 'Uploading Walkthrough & Parameters...';

        setTimeout(function() {
          vStatus.style.display = 'block';
          vStatus.style.background = 'rgba(16, 185, 129, 0.1)';
          vStatus.style.border = '1px solid #10b981';
          vStatus.style.color = '#065f46';
          vStatus.innerText = 'Thank you, ' + vName + '. Your site walkthrough has been forwarded to our engineering desk. We will review your footage and issue meeting invites via your preferred video platform shortly.';
          videoForm.reset();
          if (fileInput) fileInput.value = '';
          if (selectedChip) selectedChip.style.display = 'none';
          if (dropzoneContent) dropzoneContent.style.display = 'block';
          vBtn.disabled = false;
          if (vBtnText) vBtnText.innerText = 'Submit Walkthrough & Book Video Meeting';
        }, 1200);
      });
    }
  });
</script>

