        <details class="faq-item">
          <summary>Do I need planning permission or can I use Permitted Development Rights?</summary>
          <p>Many residential extensions, loft conversions, and commercial Class MA conversions fall under Permitted Development rights, meaning you do not require a full planning application. However, you should secure a Lawful Development Certificate (LDC) or Prior Approval to legally verify that the works meet statutory rules. We assess your site's planning history and Article 4 constraints during our initial review to recommend the fastest approval route.</p>
        </details>

        <details class="faq-item">
          <summary>When does the Party Wall etc. Act 1996 apply to my project?</summary>
          <p>The Act applies whenever you intend to cut into a shared wall (such as inserting steel beams for a loft or extension), build on or up to the boundary line, or excavate foundations within 3 meters (or 6 meters for deep piles) of a neighboring structure. You must serve statutory notices at least 1 to 2 months prior to starting works. We prepare notices, conduct photographic condition audits, and agree formal Party Wall Awards.</p>
        </details>

        <details class="faq-item">
          <summary>What is the difference between Building Regulations and Planning Permission?</summary>
          <p>Planning Permission assesses how your proposed building looks, its impact on the local neighborhood, highways, and the environment. Building Regulations focus on structural safety, thermal efficiency, fire protection, and drainage. Even if your scheme does not require Planning Permission (e.g., under Permitted Development), it almost always requires Building Regulations approval before work commences.</p>
        </details>

