<!-- =========================================================
     TAB SWITCHING & URL HASH SYNCHRONIZATION ENGINE
     ========================================================= -->
<script>
  document.addEventListener('DOMContentLoaded', function () {
    const vtabBtns = document.querySelectorAll('.vtab-btn');
    const tabPanels = document.querySelectorAll('.tab-panel');

    function activateTab(tabKey) {
      if (!tabKey) return;
      
      const targetBtn = document.querySelector(`.vtab-btn[data-tab="${tabKey}"]`);
      const targetPanel = document.getElementById(`panel-${tabKey}`);

      if (targetBtn && targetPanel) {
        vtabBtns.forEach(b => {
          b.classList.remove('is-active');
          b.setAttribute('aria-selected', 'false');
        });
        tabPanels.forEach(p => p.classList.remove('is-active'));

        targetBtn.classList.add('is-active');
        targetBtn.setAttribute('aria-selected', 'true');
        targetPanel.classList.add('is-active');

        // On smaller screens, scroll down to the panel so user sees the change
        if (window.innerWidth <= 900) {
          targetPanel.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        }
      }
    }

    vtabBtns.forEach(btn => {
      btn.addEventListener('click', function () {
        const tabKey = this.getAttribute('data-tab');
        activateTab(tabKey);
        history.replaceState(null, null, `#${tabKey}`);
      });
    });

    // Hash deep linking on page load (e.g. services.php#structural or services.php#planning)
    const initialHash = window.location.hash.replace('#', '');
    if (initialHash) {
      activateTab(initialHash);
    }
  });
</script>

