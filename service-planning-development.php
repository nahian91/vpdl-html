  <script>
    function toggleFaq(btn) {
      var item = btn.closest('.faq-unit');
      var content = item.querySelector('.faq-content');
      var isOpen = item.classList.contains('is-open');

      document.querySelectorAll('.faq-unit').forEach(function(el) {
        el.classList.remove('is-open');
        el.querySelector('button').setAttribute('aria-expanded', 'false');
        var c = el.querySelector('.faq-content');
        c.style.maxHeight = c.scrollHeight + 'px';
        requestAnimationFrame(function() {
          c.style.maxHeight = null;
        });
      });

      if (!isOpen) {
        item.classList.add('is-open');
        btn.setAttribute('aria-expanded', 'true');
        content.style.maxHeight = content.scrollHeight + 30 + 'px';

        content.addEventListener('transitionend', function handler() {
          if (item.classList.contains('is-open')) {
            content.style.maxHeight = 'none';
          }
          content.removeEventListener('transitionend', handler);
        });
      }
    }

    document.addEventListener('DOMContentLoaded', function () {
      var revealTargets = document.querySelectorAll('[data-reveal]');
      if ('IntersectionObserver' in window) {
        var observer = new IntersectionObserver(function (entries) {
          entries.forEach(function (entry) {
            if (entry.isIntersecting) {
              var target = entry.target;
              var children = target.querySelectorAll('.spec-item, .workflow-card, .deliverable-item');
              if (children.length > 0) {
                children.forEach(function (child, index) {
                  child.style.transitionDelay = (index * 0.05) + 's';
                });
              }
              target.classList.add('is-visible');
              observer.unobserve(target);
            }
          });
        }, { threshold: 0.08, rootMargin: '0px 0px -40px 0px' });
        
        revealTargets.forEach(function (el) { observer.observe(el); });
      } else {
        revealTargets.forEach(function (el) { el.classList.add('is-visible'); });
      }
    });
  </script>

