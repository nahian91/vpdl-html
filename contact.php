  <!-- Interactive Form Handling Script -->
  <script>
  document.getElementById('generalContactForm').addEventListener('submit', function(e) {
      e.preventDefault();

      // Bot protection check
      var honeypot = document.getElementById('website_hp').value;
      if (honeypot) {
          return false;
      }

      var nameInput    = document.getElementById('contactName');
      var emailInput   = document.getElementById('contactEmail');
      var subjectInput = document.getElementById('contactSubject');
      var messageInput = document.getElementById('contactMessage');
      
      var name    = nameInput.value.trim();
      var email   = emailInput.value.trim();
      var subject = subjectInput.value.trim();
      var message = messageInput.value.trim();
      
      var statusBox = document.getElementById('contactStatusBox');
      var submitBtn = document.getElementById('contactSubmitBtn');
      var btnText   = document.getElementById('btnText');
      var btnIcon   = document.getElementById('btnIcon');

      var emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

      // Reset border styles
      [nameInput, emailInput, subjectInput, messageInput].forEach(function(el) {
          el.style.borderColor = '';
      });

      // Field Validation
      if (!name || !email || !subject || !message) {
          showStatus('Please ensure all required fields marked with an asterisk (*) are populated.', 'error');
          if (!name) nameInput.style.borderColor = 'var(--brand-red)';
          if (!email) emailInput.style.borderColor = 'var(--brand-red)';
          if (!subject) subjectInput.style.borderColor = 'var(--brand-red)';
          if (!message) messageInput.style.borderColor = 'var(--brand-red)';
          return;
      }

      if (!emailPattern.test(email)) {
          showStatus('Please specify a valid corporate or private email address.', 'error');
          emailInput.style.borderColor = 'var(--brand-red)';
          emailInput.focus();
          return;
      }

      // UI Loading State
      submitBtn.disabled = true;
      submitBtn.style.opacity = '0.75';
      btnText.innerText = 'Securing & Transmitting Dispatch...';
      btnIcon.style.display = 'none';
      statusBox.style.display = 'none';

      // Submission simulation
      setTimeout(function() {
          showStatus('Thank you. Your message has been logged directly with our practice directors. An allocated consultant will respond within 24 business hours.', 'success');
          
          document.getElementById('generalContactForm').reset();
          submitBtn.disabled = false;
          submitBtn.style.opacity = '1';
          btnText.innerText = 'Transmit Direct Inquiry';
          btnIcon.style.display = 'inline-block';
      }, 1000);

      function showStatus(msg, type) {
          statusBox.innerText = msg;
          statusBox.style.display = 'block';

          if (type === 'error') {
              statusBox.className = 'form-status';
              statusBox.style.background = 'rgba(237, 28, 36, 0.12)';
              statusBox.style.border = '1px solid var(--brand-red)';
              statusBox.style.color = '#FFF';
          } else {
              statusBox.className = 'form-status success';
              statusBox.style.removeProperty('background');
              statusBox.style.removeProperty('border');
              statusBox.style.removeProperty('color');
          }
      }
  });
  </script>

